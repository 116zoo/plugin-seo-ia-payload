import { expect, test } from '@playwright/test'

test('French editorial selection applies only chosen fields, related drafts and graph', async ({ page }) => {
  expect((await page.request.post('/api/users/login', { data: { email: 'admin@example.test', password: 'local-browser-fixture-password' } })).ok()).toBeTruthy()
  const created = await page.request.post('/api/posts?locale=fr', { data: { title: 'Editorial fixture FR', slug: 'editorial-fr', excerpt: 'Chapô initial FR', content: 'Texte français conservé.' } })
  expect(created.ok()).toBeTruthy()
  const { doc } = await created.json()
  await page.request.patch(`/api/posts/${doc.id}?locale=en`, { data: { title: 'Editorial fixture EN', slug: 'editorial-en', excerpt: 'Original English excerpt', content: 'Preserved English text.' } })
  await page.goto(`/admin/collections/posts/${doc.id}?locale=fr`)
  const panel = page.getByRole('region', { name: /SEO IA/ })
  await panel.getByRole('button', { name: /Générer une proposition/ }).click()
  await expect(panel.getByRole('heading', { name: 'Contenu éditorial', exact: true })).toBeVisible()
  await expect(panel.getByText(/Content.*conservé/)).toBeVisible()
  await expect(panel.getByRole('checkbox', { name: /content/i })).toHaveCount(0)
  const apply = panel.getByRole('button', { name: /^Appliquer/ })
  await expect(apply).toBeDisabled()
  await panel.getByRole('checkbox', { name: 'Chapô (excerpt)', exact: true }).check()
  await panel.getByRole('checkbox', { name: 'Tags (tags)', exact: true }).check()
  await expect(apply).toBeDisabled()
  await expect(panel.getByRole('alert')).toContainText(/éléments liés requis/i)
  await panel.getByRole('checkbox', { name: /Créer.*Art numérique/ }).check()
  await panel.getByRole('checkbox', { name: /Appliquer le graphe sémantique/ }).check()
  const preview = panel.getByTestId('editorial-graph-preview')
  await expect(preview).toContainText('Chapô proposé FR')
  await expect(preview).toContainText('Art numérique')
  await expect(preview).not.toContainText('Titre éditorial proposé FR')
  await expect(panel.getByRole('checkbox', { name: 'JSON-LD', exact: true })).toBeDisabled()
  const request = page.waitForRequest((request) => request.url().endsWith('/api/nim-seo/apply'))
  await apply.click()
  expect((await request).postDataJSON()).toMatchObject({ groups: [], editorialPaths: ['excerpt', 'tags'], relatedDraftIDs: ['new-tag'], applyGraph: true, locale: 'fr' })
  await expect(panel.getByRole('status')).toContainText(/appliquée/)
  const fr = await (await page.request.get(`/api/posts/${doc.id}?locale=fr&fallback-locale=none&draft=true&depth=0`)).json()
  const en = await (await page.request.get(`/api/posts/${doc.id}?locale=en&fallback-locale=none&draft=true&depth=0`)).json()
  expect(fr.title).toBe('Editorial fixture FR')
  expect(fr.excerpt).toBe('Chapô proposé FR')
  expect(fr.content).toBe('Texte français conservé.')
  expect(en.excerpt).toBe('Original English excerpt')
  expect(en.content).toBe('Preserved English text.')
  expect(fr.tags).toHaveLength(1)
  expect(JSON.stringify(fr.seo.schema)).not.toContain('draft:new-tag')
  expect(JSON.stringify(fr.seo.schema)).not.toContain('Titre éditorial proposé FR')
})

test('English editorial review resets every selection across proposals and locales', async ({ page }) => {
  await page.request.post('/api/users/login', { data: { email: 'admin@example.test', password: 'local-browser-fixture-password' } })
  const { doc } = await (await page.request.post('/api/posts?locale=en', { data: { title: 'Editorial fixture EN', slug: 'editorial-reset', content: 'English source.' } })).json()
  await page.goto(`/admin/collections/posts/${doc.id}?locale=en`)
  const panel = page.getByRole('region', { name: /AI SEO/ })
  await panel.getByRole('button', { name: /Generate proposal/ }).click()
  await expect(panel.getByRole('heading', { name: 'Editorial content', exact: true })).toBeVisible()
  await expect(panel.getByText(/Content.*preserved/)).toBeVisible()
  await panel.getByRole('checkbox', { name: 'Excerpt (excerpt)', exact: true }).check()
  await panel.getByRole('checkbox', { name: /Apply semantic graph/ }).check()
  await expect(panel.getByTestId('editorial-graph-preview')).toContainText('Proposed English excerpt')
  await expect(panel.getByTestId('editorial-graph-preview')).not.toContainText('Digital art')
  await panel.getByRole('button', { name: /Generate proposal/ }).click()
  await expect(panel.getByRole('checkbox', { name: 'Excerpt (excerpt)', exact: true })).not.toBeChecked()
  await expect(panel.getByRole('checkbox', { name: /Apply semantic graph/ })).not.toBeChecked()
  await expect(panel.getByRole('button', { name: /^Apply/ })).toBeDisabled()
  await page.goto(`/admin/collections/posts/${doc.id}?locale=fr`)
  await expect(page.getByText('Proposed English excerpt')).toHaveCount(0)
  await expect(page.getByRole('button', { name: /^Appliquer/ })).toHaveCount(0)
})
